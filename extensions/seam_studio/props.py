"""Root SEAM property groups (owner: integrator). Domain groups live in their packages."""

import bpy
from bpy.props import (CollectionProperty, EnumProperty, FloatProperty, IntProperty, PointerProperty,
                       StringProperty, BoolProperty)

from .engine.props import SEAM_PG_EngineSettings
from .link.props import SEAM_PG_Link
from .paint.props import SEAM_PG_RasterDoc
from .seam_core import SCHEMA_VERSION
from .seam_core.units import UNITS
from .vector.props import SEAM_PG_Artboard, SEAM_PG_ShapeRecipe, SEAM_PG_Style

ROLES = [
    ("NONE", "None", "Not managed by SEAM"),
    ("CANVAS_ROOT", "Canvas", "Root of the 2D canvas"),
    ("ARTBOARD", "Artboard", "Artboard frame"),
    ("GROUP", "Group", "Vector group"),
    ("SHAPE", "Shape", "Vector path"),
    ("TEXT", "Text", "Editable text"),
    ("RASTER", "Raster", "Raster painting canvas"),
    ("GUIDE", "Guide", "Guide line"),
    ("STROKE", "Stroke", "Derived stroke geometry"),
    ("OUTLINE", "Outline", "Derived text outline"),
    ("CLIP_RESULT", "Clip Result", "Derived clipped geometry"),
    ("RESULT", "3D Result", "Generated by a live link"),
    ("INTERNAL", "Internal", "SEAM internal helper"),
]


class SEAM_PG_DocSettings(bpy.types.PropertyGroup):
    units: EnumProperty(name="Units", items=[(u, u.lower() if u != "PX" else "px", "") for u in UNITS], default="PX")
    dpi: FloatProperty(name="DPI", min=1.0, max=4800.0, default=96.0)
    active_artboard_id: StringProperty()
    canvas_ready: BoolProperty(default=False)


def _tag_owner(self, context):
    obj = getattr(self, "id_data", None)
    if obj is not None and hasattr(obj, "update_tag"):
        obj.update_tag()


class SEAM_PG_Object(bpy.types.PropertyGroup):
    id: StringProperty(name="SEAM ID")
    role: EnumProperty(name="Role", items=ROLES, default="NONE")
    owner_id: StringProperty(name="Owner")
    raster_id: StringProperty(name="Raster Document")
    style: PointerProperty(type=SEAM_PG_Style)
    shape: PointerProperty(type=SEAM_PG_ShapeRecipe)
    artboard: PointerProperty(type=SEAM_PG_Artboard)
    clip_source: PointerProperty(name="Clip To", type=bpy.types.Object, update=_tag_owner)


class SEAM_PG_Scene(bpy.types.PropertyGroup):
    schema_version: IntProperty(default=SCHEMA_VERSION)
    doc: PointerProperty(type=SEAM_PG_DocSettings)
    links: CollectionProperty(type=SEAM_PG_Link)
    active_link_index: IntProperty(default=0)
    rasters: CollectionProperty(type=SEAM_PG_RasterDoc)
    active_raster_index: IntProperty(default=0)
    engine: PointerProperty(type=SEAM_PG_EngineSettings)


classes = (SEAM_PG_DocSettings, SEAM_PG_Object, SEAM_PG_Scene)


def register():
    bpy.types.Object.seam = PointerProperty(type=SEAM_PG_Object)
    bpy.types.Scene.seam = PointerProperty(type=SEAM_PG_Scene)


def unregister():
    for owner in (bpy.types.Scene, bpy.types.Object):
        if hasattr(owner, "seam"):
            del owner.seam
