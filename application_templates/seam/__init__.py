"""SEAM Studio application template (owner: shell).

Selected with ``blender --app-template seam`` (``scripts/seam-studio`` does this). The template

* enables the ``seam_studio`` add-on (legacy add-on in the user scripts path, or the extension
  ``bl_ext.<repo>.seam_studio`` when installed as one) and keeps it enabled in the profile preferences,
* ships ``startup.blend`` (workspaces Vector, Paint, Model, Split + native ones; built by
  ``scripts/build_template.py``) and ``splash.png`` (generated by ``scripts/make_splash.py``),
* after every *new* file (startup, File > New) makes sure the canvas exists, applies the new-document
  preferences and fits the canvas views. If ``startup.blend`` is missing or stale it recreates the SEAM
  workspaces by running ``seam.workspace_repair`` once the window is up.

Opening an existing .blend never alters its content.
"""

import sys

import bpy
from bpy.app.handlers import persistent

ADDON = "seam_studio"
_state = {"module": None, "error": None}
_msgbus_owner = object()
_framed = set()   # SEAM workspaces already fitted in this new document


def _find_module_name():
    """Module name of the add-on on the add-on path (and make it importable: templates register before
    Blender has put the user add-on directory on ``sys.path``)."""
    import os
    import addon_utils
    for mod in addon_utils.modules(refresh=False):
        name = getattr(mod, "__name__", "")
        if name == ADDON or name.endswith("." + ADDON):
            if "." not in name:  # legacy add-on: <addons dir>/seam_studio/__init__.py
                addons_dir = os.path.dirname(os.path.dirname(os.path.abspath(mod.__file__)))
                if addons_dir not in sys.path:
                    sys.path.append(addons_dir)
            return name
    return None


def _enable_addon():
    import addon_utils
    name = _find_module_name()
    if name is None:
        _state["error"] = (f"add-on '{ADDON}' not found on the add-on path; run scripts/bootstrap.sh or install the "
                           "SEAM Studio add-on zip. The SEAM template UI is unavailable.")
        print("SEAM template:", _state["error"])
        return None
    # default_set: Blender resets add-ons that are not in the preferences list right after templates register
    mod = addon_utils.enable(name, default_set=True, persistent=True, handle_error=None)
    if mod is None:
        _state["error"] = f"enabling add-on '{name}' failed (see the console)"
        print("SEAM template:", _state["error"])
        return None
    _state["module"] = name
    return sys.modules[name]


def _timer_new_document(module_name: str):
    """One-shot after the window is up: repair/frame views for a new document."""
    from importlib import import_module
    ws = import_module(module_name + ".ui.workspaces")
    names = {w.name for w in bpy.data.workspaces}
    missing = [n for n in ws.SEAM_WORKSPACES if n not in names]
    wm = bpy.context.window_manager
    if missing and len(wm.windows):
        try:
            with bpy.context.temp_override(window=wm.windows[0], screen=wm.windows[0].screen):
                bpy.ops.seam.workspace_repair("INVOKE_DEFAULT", activate="Vector")
        except Exception as exc:
            print("SEAM template: workspace repair failed:", exc)
    else:
        ws.frame_canvas_views()
        win = wm.windows[0] if len(wm.windows) else None
        if win is not None:
            _framed.add(win.workspace.name)
    return None


def _frame_current_workspace():
    """First visit of a SEAM workspace in a new (unsaved) document: fit its canvas view to the real window size
    (``startup.blend`` was built with a different window size)."""
    module_name = _state["module"]
    wm = bpy.context.window_manager
    if not module_name or bpy.data.filepath or not len(wm.windows):
        return None
    from importlib import import_module
    ws = import_module(module_name + ".ui.workspaces")
    name = wm.windows[0].workspace.name
    if name in ws.SEAM_WORKSPACES and name not in _framed:
        _framed.add(name)
        ws.frame_canvas_views()
    return None


def _on_workspace_change():
    bpy.app.timers.register(_frame_current_workspace, first_interval=0.4)


def _subscribe_workspace_changes():
    bpy.msgbus.clear_by_owner(_msgbus_owner)  # file loads drop subscriptions; always re-subscribe
    bpy.msgbus.subscribe_rna(key=(bpy.types.Window, "workspace"), owner=_msgbus_owner, args=(),
                             notify=_on_workspace_change)


def _clear_factory_scene():
    """Without ``startup.blend`` Blender loads its factory scene: drop the untouched default cube, camera and light
    so a new SEAM document starts empty (anything the user changed or added is kept)."""
    import os
    if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), "startup.blend")):
        return
    defaults = {"Cube": "MESH", "Camera": "CAMERA", "Light": "LIGHT"}
    objs = list(bpy.data.objects)
    if {o.name for o in objs} != set(defaults) or any(o.type != defaults[o.name] for o in objs):
        return
    for ob in objs:
        bpy.data.objects.remove(ob)
    for col in list(bpy.data.collections):
        if col.name == "Collection" and not col.objects and not col.children:
            bpy.data.collections.remove(col)


@persistent
def _on_load_post(*_args):
    module_name = _state["module"]
    if not module_name or bpy.data.filepath:
        return  # existing files are never touched
    from importlib import import_module
    _clear_factory_scene()
    try:
        document = import_module(module_name + ".ui.document")
        document.ensure_document(bpy.context.scene)
        document.apply_new_document_defaults(bpy.context.scene)
    except Exception as exc:
        print("SEAM template: preparing the new document failed:", exc)
        return
    if not bpy.app.background:
        _framed.clear()
        _subscribe_workspace_changes()
        bpy.app.timers.register(lambda: _timer_new_document(module_name), first_interval=0.5)


def register():
    _enable_addon()
    if _on_load_post not in bpy.app.handlers.load_post:
        bpy.app.handlers.load_post.append(_on_load_post)


def unregister():
    while _on_load_post in bpy.app.handlers.load_post:
        bpy.app.handlers.load_post.remove(_on_load_post)
    bpy.msgbus.clear_by_owner(_msgbus_owner)
    _state.update(module=None, error=None)
